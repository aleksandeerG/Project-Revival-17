using System.Text;

namespace Revival.Launcher.Core;

public sealed record ServerProfile(
    string Host,
    int RedirectorPort,
    int AccountsPort,
    int BlazePort,
    int FutPort,
    int CdnPort);

public enum ConfigurationError
{
    None = 0,
    HostMissing,
    HostTooLong,
    HostInvalid,
    PortOutOfRange,
    CredentialMissing,
    CredentialContainsNewline,
    PinMissingOrMalformed,
}

public static class ShimConfiguration
{
    public const string IniFileName = "fifa17-revival.ini";

    public const int MaxHostLength = 16;

    public static bool TryGenerate(
        ServerProfile profile,
        string username,
        string password,
        string certificatePin,
        bool debugLogging,
        out byte[] contents,
        out ConfigurationError error)
    {
        ArgumentNullException.ThrowIfNull(profile);
        contents = [];

        if (string.IsNullOrWhiteSpace(profile.Host))
        {
            error = ConfigurationError.HostMissing;
            return false;
        }

        if (Encoding.UTF8.GetByteCount(profile.Host) > MaxHostLength)
        {
            error = ConfigurationError.HostTooLong;
            return false;
        }

        if (!ServerEndpoint.IsValidHost(profile.Host))
        {
            error = ConfigurationError.HostInvalid;
            return false;
        }

        foreach (int port in new[]
                 {
                     profile.RedirectorPort, profile.AccountsPort,
                     profile.BlazePort, profile.FutPort, profile.CdnPort,
                 })
        {
            if (port is < 1 or > 65535)
            {
                error = ConfigurationError.PortOutOfRange;
                return false;
            }
        }

        if (string.IsNullOrEmpty(username) || string.IsNullOrEmpty(password))
        {
            error = ConfigurationError.CredentialMissing;
            return false;
        }

        if (ContainsNewline(username) || ContainsNewline(password))
        {
            error = ConfigurationError.CredentialContainsNewline;
            return false;
        }

        string pin = (certificatePin ?? string.Empty)
            .Replace(":", "", StringComparison.Ordinal).Trim();
        if (pin.Length != 64 || !pin.All(Uri.IsHexDigit))
        {
            error = ConfigurationError.PinMissingOrMalformed;
            return false;
        }

        var builder = new StringBuilder();
        builder.AppendLine("; Generated by the Project Revival 17 launcher. Edits are overwritten.");
        builder.AppendLine();
        builder.AppendLine("[Login]");
        builder.AppendLine($"Host = {profile.Host}");
        builder.AppendLine($"Port = {profile.RedirectorPort}");
        builder.AppendLine($"Debug = {(debugLogging ? 1 : 0)}");
        builder.AppendLine();
        builder.AppendLine("[Credentials]");
        builder.AppendLine($"Username = {username}");
        builder.AppendLine($"Password = {password}");
        builder.AppendLine();
        builder.AppendLine("[Patch]");
        builder.AppendLine("; Required: the redirector presents a self-signed certificate.");
        builder.AppendLine("accept_certs = 1");
        builder.AppendLine("; Required: without it the FUT hub never finishes loading.");
        builder.AppendLine("fifa_points = 1");
        builder.AppendLine("transfer_pile_capacity = 1");
        builder.AppendLine("squad_rename_guard = 1");
        builder.AppendLine("force_flux_components_ready = 1");
        builder.AppendLine("; Reconnaissance detours. Not for player installations.");
        builder.AppendLine("fut_probes = 0");
        builder.AppendLine("force_profile_advance = 0");
        builder.AppendLine("apt_vm_probe = 0");
        builder.AppendLine("apt_byte_watch = 0");
        builder.AppendLine("script_publish_watch = 0");
        builder.AppendLine();
        builder.AppendLine("[Server]");
        builder.AppendLine($"login_port = {profile.AccountsPort}");
        builder.AppendLine($"fut_port   = {profile.FutPort}");
        builder.AppendLine($"cdn_port   = {profile.CdnPort}");
        builder.AppendLine($"blaze_port = {profile.BlazePort}");
        builder.AppendLine($"certificate_pin = {pin.ToUpperInvariant()}");

        contents = new UTF8Encoding(encoderShouldEmitUTF8Identifier: false)
            .GetBytes(builder.ToString());

        error = ConfigurationError.None;
        return true;
    }

    private static bool ContainsNewline(string value) =>
        value.Contains('\n', StringComparison.Ordinal) ||
        value.Contains('\r', StringComparison.Ordinal);
}
